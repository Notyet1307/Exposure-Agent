export MODEL_QUALIFICATION_ALLOW_BAIZHI_TEST="${MODEL_QUALIFICATION_ALLOW_BAIZHI_TEST:-false}"
export AI_INVESTIGATION_ALLOW_BAIZHI_TEST="${AI_INVESTIGATION_ALLOW_BAIZHI_TEST:-false}"
