export GOVERNANCE_RUNNER_BUILD_VERSION
: "${ARTIFACT_HOST_PATH:?ARTIFACT_HOST_PATH is required}"

input=${1:?input template is required}
output=${2:?output path is required}
export CLOUDATLAS_ASSETS_CAPSET_TOKEN="${CLOUDATLAS_ASSETS_CAPSET_TOKEN:-}"
export CLOUDATLAS_ROOT_DOMAINS_CAPSET_TOKEN="${CLOUDATLAS_ROOT_DOMAINS_CAPSET_TOKEN:-}"
export CLOUDATLAS_DNS_CAPSET_TOKEN="${CLOUDATLAS_DNS_CAPSET_TOKEN:-}"
export CLOUDATLAS_SUBDOMAIN_CAPSET_TOKEN="${CLOUDATLAS_SUBDOMAIN_CAPSET_TOKEN:-}"
export CLOUDATLAS_CERT_CAPSET_TOKEN="${CLOUDATLAS_CERT_CAPSET_TOKEN:-}"
export CLOUDATLAS_OPENPORT_CAPSET_TOKEN="${CLOUDATLAS_OPENPORT_CAPSET_TOKEN:-}"
export CLOUDATLAS_WEB_CAPSET_TOKEN="${CLOUDATLAS_WEB_CAPSET_TOKEN:-}"
export CLOUDATLAS_DIR_CAPSET_TOKEN="${CLOUDATLAS_DIR_CAPSET_TOKEN:-}"
export CLOUDATLAS_APPFINGER_CAPSET_TOKEN="${CLOUDATLAS_APPFINGER_CAPSET_TOKEN:-}"
export CLOUDATLAS_CRAWLER_CAPSET_TOKEN="${CLOUDATLAS_CRAWLER_CAPSET_TOKEN:-}"
export CLOUDATLAS_SEED_ENTERPRISE_CAPSET_TOKEN="${CLOUDATLAS_SEED_ENTERPRISE_CAPSET_TOKEN:-}"
